// Command gen reads a vendored copy of the Unicode Character Database's
// UnicodeData.txt and emits arabic/tables.go: a map from every Arabic
// presentation-form codepoint (Arabic Presentation Forms-A, U+FB50-U+FDFF,
// and Forms-B, U+FE70-U+FEFF) to the letter sequence its Unicode
// compatibility decomposition expands to.
//
// Only entries whose decomposition field carries one of the four
// positional tags <isolated>, <initial>, <medial>, <final> are included.
// That is deliberately narrower than a full NFKC/compatibility
// decomposition (see the "Decision to make" note in plan.md's Phase 4):
// it picks up every contextual letter form, ligature, and presentation
// form of a standalone diacritic in those two blocks (verified against
// UnicodeData.txt: this includes ﻻ LAM WITH ALEF, ﷲ ALLAH, ﷺ
// SALLALLAHOU ALAYHE WASALLAM, ﷻ JALLAJALALOUHOU, and the FE70-FE7F
// isolated/medial harakat forms), while leaving out anything NFKC would
// also fold that has nothing to do with Arabic presentation forms
// (superscripts, full-width Latin, roman numerals, ...).
//
// A handful of entries in these two blocks have no decomposition at all
// (dot/ring diacritic symbols, and the BISMILLAH ligature U+FDFD, which
// Unicode deliberately leaves undecomposed since it stands for a whole
// phrase). Those are correctly absent from the generated table, not an
// oversight; see docs/NORMALIZATION.md.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var decompRE = regexp.MustCompile(`^<(isolated|initial|medial|final)>\s+(.+)$`)

type entry struct {
	codepoint rune
	name      string
	expansion string
}

func main() {
	in := flag.String("in", "gen/UnicodeData.txt", "path to UnicodeData.txt")
	out := flag.String("out", "tables.go", "output Go source path")
	ucdVersion := flag.String("ucd-version", "18.0.0", "Unicode version, for the generated file's header comment")
	flag.Parse()

	entries, err := parse(*in)
	if err != nil {
		log.Fatalf("gen: %v", err)
	}

	src, err := render(entries, *ucdVersion)
	if err != nil {
		log.Fatalf("gen: %v", err)
	}

	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("gen: writing %s: %v", *out, err)
	}
	fmt.Printf("gen: wrote %d presentation-form entries to %s\n", len(entries), *out)
}

func parse(path string) ([]entry, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var entries []entry
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 0, 64*1024), 1024*1024)

	for scanner.Scan() {
		fields := strings.Split(scanner.Text(), ";")
		if len(fields) < 6 {
			continue
		}

		cp64, err := strconv.ParseInt(fields[0], 16, 32)
		if err != nil {
			return nil, fmt.Errorf("bad codepoint %q: %w", fields[0], err)
		}
		cp := rune(cp64)

		inFormsA := cp >= 0xFB50 && cp <= 0xFDFF
		inFormsB := cp >= 0xFE70 && cp <= 0xFEFF
		if !inFormsA && !inFormsB {
			continue
		}

		m := decompRE.FindStringSubmatch(fields[5])
		if m == nil {
			continue // no decomposition, or a tag other than the four we want.
		}

		expansion, err := decodeCodepoints(m[2])
		if err != nil {
			return nil, fmt.Errorf("U+%04X: %w", cp, err)
		}

		entries = append(entries, entry{codepoint: cp, name: fields[1], expansion: expansion})
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}

	sort.Slice(entries, func(i, j int) bool { return entries[i].codepoint < entries[j].codepoint })
	return entries, nil
}

// decodeCodepoints turns a space-separated list of hex codepoints (as they
// appear after a decomposition's positional tag) into the string they
// spell out.
func decodeCodepoints(field string) (string, error) {
	var b strings.Builder
	for _, tok := range strings.Fields(field) {
		v, err := strconv.ParseInt(tok, 16, 32)
		if err != nil {
			return "", fmt.Errorf("bad decomposition codepoint %q: %w", tok, err)
		}
		b.WriteRune(rune(v))
	}
	return b.String(), nil
}

func render(entries []entry, ucdVersion string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by arabic/gen from UnicodeData.txt (Unicode %s). DO NOT EDIT.\n", ucdVersion)
	fmt.Fprintf(&b, "// Regenerate with: go generate ./arabic/...\n")
	fmt.Fprintf(&b, "// See arabic/gen/README.md for provenance and arabic/gen/main.go for the filter.\n\n")
	fmt.Fprintf(&b, "package arabic\n\n")
	fmt.Fprintf(&b, "// presentationForms maps an Arabic presentation-form codepoint to the letter\n")
	fmt.Fprintf(&b, "// sequence its Unicode compatibility decomposition expands to. See the\n")
	fmt.Fprintf(&b, "// package comment in gen/main.go for exactly which entries qualify.\n")
	fmt.Fprintf(&b, "var presentationForms = map[rune]string{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t0x%04X: %q, // %s\n", e.codepoint, e.expansion, e.name)
	}
	fmt.Fprintf(&b, "}\n")

	return format.Source([]byte(b.String()))
}
